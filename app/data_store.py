"""
app/data_store.py
-------------------
Loads the read-only catalog (cities, hotels, room types, rooms,
restaurants, tables, dishes, activities, customers) from the CSV files
generated by the `generator/` script, and implements the `BookingStore`:
the in-memory + SQLite-backed collection of bookings, with the overlap /
capacity checks used by both the availability and the booking-creation
endpoints.

Visibility rule (see README.md): whenever bookings are read (for listing,
availability checks, or overlap validation), the set considered is always
"seed bookings" + "bookings created by the requesting IP" — never bookings
created by a different IP. This is what keeps workshop attendees from
colliding with each other.
"""
from __future__ import annotations

import csv
import itertools
import threading
from datetime import date, datetime
from pathlib import Path
from typing import Optional

from . import config, db

BLOCKING_STATUSES = {"pending", "confirmed", "completed"}


# ---------------------------------------------------------------------------
# CSV parsing helpers
# ---------------------------------------------------------------------------
def _read_csv_rows(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        raise FileNotFoundError(
            f"Seed data file not found: {path}. Did you set DATA_DIR correctly, "
            f"and does it contain the CSVs produced by the generator?"
        )
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _b(v: str) -> bool:
    return str(v).strip().lower() in ("true", "1", "yes")


def _lst(v: str) -> list[str]:
    v = (v or "").strip()
    return v.split(";") if v else []


def _i(v, default=None):
    v = v.strip() if isinstance(v, str) else v
    if v in (None, ""):
        return default
    return int(float(v))


def _f(v, default=None):
    v = v.strip() if isinstance(v, str) else v
    if v in (None, ""):
        return default
    return float(v)


def _d(v) -> date:
    return datetime.strptime(v.strip(), "%Y-%m-%d").date()


def _dt(v) -> datetime:
    return datetime.strptime(v.strip(), "%Y-%m-%d %H:%M:%S")


# ---------------------------------------------------------------------------
# Catalog loaders
# ---------------------------------------------------------------------------
def _load_cities(path: Path) -> list[dict]:
    return [{"city_id": _i(r["city_id"]), "name": r["name"]} for r in _read_csv_rows(path)]


def _load_hotels(path: Path) -> list[dict]:
    out = []
    for r in _read_csv_rows(path):
        out.append({
            "hotel_id": _i(r["hotel_id"]), "name": r["name"], "description": r["description"],
            "category": _i(r["category"]), "type": r["type"], "city": r["city"],
            "check_in_time": r["check_in_time"], "check_out_time": r["check_out_time"],
            "reception_24h": _b(r["reception_24h"]), "services": _lst(r["services"]),
            "pet_friendly": _b(r["pet_friendly"]), "accessible": _b(r["accessible"]),
            "rating": _f(r["rating"]), "review_count": _i(r["review_count"]),
            "price_range": r["price_range"],
        })
    return out


def _load_room_types(path: Path) -> list[dict]:
    out = []
    for r in _read_csv_rows(path):
        out.append({
            "room_type_id": _i(r["room_type_id"]), "hotel_id": _i(r["hotel_id"]),
            "name": r["name"], "description": r["description"],
            "max_adults": _i(r["max_adults"]), "max_children": _i(r["max_children"]),
            "bed_configuration": r["bed_configuration"], "size_m2": _i(r["size_m2"]),
            "bathroom_type": r["bathroom_type"], "services": _lst(r["services"]),
            "accessible": _b(r["accessible"]), "base_price_per_night": _f(r["base_price_per_night"]),
            "breakfast_included": _b(r["breakfast_included"]),
            "cancellation_policy": r["cancellation_policy"],
        })
    return out


def _load_rooms(path: Path) -> list[dict]:
    out = []
    for r in _read_csv_rows(path):
        out.append({
            "room_id": _i(r["room_id"]), "hotel_id": _i(r["hotel_id"]),
            "room_type_id": _i(r["room_type_id"]), "room_number": r["room_number"],
            "floor": _i(r["floor"]), "status": r["status"], "notes": r["notes"],
        })
    return out


def _load_restaurants(path: Path) -> list[dict]:
    out = []
    for r in _read_csv_rows(path):
        out.append({
            "restaurant_id": _i(r["restaurant_id"]), "name": r["name"], "description": r["description"],
            "cuisine_types": _lst(r["cuisine_types"]), "city": r["city"],
            "opening_hours": r["opening_hours"], "price_range": r["price_range"],
            "rating": _f(r["rating"]), "review_count": _i(r["review_count"]),
            "services": _lst(r["services"]), "accessible": _b(r["accessible"]),
            "pet_friendly": _b(r["pet_friendly"]), "dress_code": r["dress_code"],
            "max_capacity": _i(r["max_capacity"]),
        })
    return out


def _load_tables(path: Path) -> list[dict]:
    out = []
    for r in _read_csv_rows(path):
        out.append({
            "table_id": _i(r["table_id"]), "restaurant_id": _i(r["restaurant_id"]),
            "table_number": _i(r["table_number"]), "capacity": _i(r["capacity"]),
            "location": r["location"], "accessible": _b(r["accessible"]), "status": r["status"],
        })
    return out


def _load_dishes(path: Path) -> list[dict]:
    out = []
    for r in _read_csv_rows(path):
        out.append({
            "dish_id": _i(r["dish_id"]), "restaurant_id": _i(r["restaurant_id"]),
            "name": r["name"], "description": r["description"], "category": r["category"],
            "price": _f(r["price"]), "currency": r["currency"],
            "ingredients": _lst(r["ingredients"]), "allergens": _lst(r["allergens"]),
            "dietary_tags": _lst(r["dietary_tags"]), "spicy_level": _i(r["spicy_level"]),
            "calories": _i(r["calories"]), "available": _b(r["available"]),
        })
