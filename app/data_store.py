def _load_activities(path: Path) -> list[dict]:
    out = []
    for r in _read_csv_rows(path):
        out.append({
            "activity_id": _i(r["activity_id"]), "name": r["name"], "description": r["description"],
            "activity_type": r["activity_type"], "category": r["category"], "city": r["city"],
            "opening_hours": r["opening_hours"], "duration_minutes": _i(r["duration_minutes"]),
            "min_age": _i(r["min_age"]), "max_age": _i(r["max_age"], default=None),
            "accessible": _b(r["accessible"]), "indoor_outdoor": r["indoor_outdoor"],
            "max_capacity": _i(r["max_capacity"]), "rating": _f(r["rating"]),
            "review_count": _i(r["review_count"]), "services": _lst(r["services"]),
            "price": _f(r["price"]),
        })
